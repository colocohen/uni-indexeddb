#!/usr/bin/env node
'use strict';

/**
 * uni-indexeddb browser bundler.
 *
 * Concatenates the CJS modules into one self-contained browser file.
 * No external tools needed — just: node build-browser.js
 *
 * Produces:
 *   dist/uni-indexeddb.js — for browser tabs / Service Workers / Web Workers.
 *                           Sets the global `uniIndexedDB` (the createDB
 *                           function from index.js), which sw_db.js calls.
 *
 * The LevelDB engine is Node-only (fs, path, classic-level) and is not
 * bundled — index.js only requires it when running under Node.
 */

var fs = require('fs');
var path = require('path');

var ROOT = __dirname;

// [module name, file]. The name is what _require resolves to after the
// './', './src/' prefix and '.js' suffix are stripped.
var MODULES = [
    ['keys',             'src/keys.js'],
    ['binary',           'src/binary.js'],
    ['engine-indexeddb', 'src/engine-indexeddb.js'],
    ['core',             'src/core.js'],
    ['index',            'index.js']
];

function read(file) {
    var fullPath = path.join(ROOT, file);
    if (!fs.existsSync(fullPath)) {
        console.error('  [missing] ' + file);
        process.exit(1);
    }
    return fs.readFileSync(fullPath, 'utf8');
}

function wrapModule(name, code) {
    return '// --- ' + name + ' ---\n' +
           '_modules["' + name + '"] = (function(module, exports, require) {\n' +
           code + '\n' +
           'return module.exports;\n' +
           '})({exports:{}}, {}, _require);\n\n';
}

function buildBundle() {
    var out = '/* uni-indexeddb — browser bundle. Generated by build-browser.js, do not edit. */\n' +
              '(function(root) {\n' +
              '"use strict";\n\n' +
              'var _modules = {};\n' +
              'function _require(name) {\n' +
              '    name = name.replace(/^\\.\\//, "").replace(/^src\\//, "").replace(/\\.js$/, "");\n' +
              '    if (!(name in _modules)) throw new Error("Module not found: " + name);\n' +
              '    return _modules[name];\n' +
              '}\n\n';

    for (var i = 0; i < MODULES.length; i++) {
        out += wrapModule(MODULES[i][0], read(MODULES[i][1]));
    }

    out += 'root.uniIndexedDB = _modules["index"];\n';
    out += '})(typeof globalThis !== "undefined" ? globalThis :\n';
    out += ' typeof self !== "undefined" ? self :\n';
    out += ' typeof window !== "undefined" ? window : this);\n';

    return out;
}

var DIST = path.join(ROOT, 'dist');
if (!fs.existsSync(DIST)) fs.mkdirSync(DIST);

var bundle = buildBundle();
fs.writeFileSync(path.join(DIST, 'uni-indexeddb.js'), bundle);
console.log('  dist/uni-indexeddb.js (' + (bundle.length / 1024).toFixed(1) + ' KB)');
